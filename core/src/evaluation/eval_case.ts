import {Content, FunctionCall, FunctionResponse, Part} from '@google/genai';

import {AppDetails} from './app_details.js';
import {Rubric} from './eval_rubrics.js';

/**
 * Container for the intermediate data that an agent generates as it responds
 * with a final answer.
 */
export interface IntermediateData {
  /** Tool use trajectory in chronological order. */
  toolUses: FunctionCall[];

  /** Tool response trajectory in chronological order. */
  toolResponses: FunctionResponse[];

  /**
   * Intermediate responses generated by sub-agents to convey progress or
   * status in a multi-agent system, distinct from the final response. Each
   * entry is a tuple of the author (usually the sub-agent name) and the parts
   * of the response.
   */
  intermediateResponses: Array<[string, Part[]]>;
}

/**
 * A record of a specific point in the agent's invocation: an agent reply, a
 * request to use a tool (function call), or a tool result.
 *
 * This structure is a projection of `Event` intended for the evaluation
 * system.
 */
export interface InvocationEvent {
  /** The name of the agent that authored this event. */
  author: string;

  /** The content of the event. */
  content?: Content;
}

/** A container for the events that occur during an invocation. */
export interface InvocationEvents {
  /** The invocation events, in chronological order. */
  invocationEvents: InvocationEvent[];
}

/** A single invocation: one user turn and the agent's reaction to it. */
export interface Invocation {
  /** Unique identifier for the invocation. */
  invocationId?: string;

  /** Content provided by the user in this invocation. */
  userContent: Content;

  /** Final response from the agent. */
  finalResponse?: Content;

  /**
   * Intermediate steps generated as a part of the agent execution. For a
   * multi-agent system, these show the route the agent took to the final
   * response.
   */
  intermediateData?: IntermediateData | InvocationEvents;

  /** Timestamp of the invocation, mainly for debugging. */
  creationTimestamp?: number;

  /** Rubrics that apply only to this invocation. */
  rubrics?: Rubric[];

  /** Details about the app that was used for this invocation. */
  appDetails?: AppDetails;
}

/**
 * Scenario for a conversation between a simulated user and the agent under
 * test.
 */
export interface ConversationScenario {
  /**
   * The fixed first user message given to the agent. Any later user messages
   * come from the system that simulates the user.
   */
  startingPrompt: string;

  /**
   * The plan that the user simulator follows as it plays out the
   * conversation, for example "First, book a one-way flight from SFO to LAX
   * for next Tuesday. Once confirmed, rent a car for three days."
   */
  conversationPlan: string;
}

/** Returns true when `data` is an {@link InvocationEvents} container. */
export function isInvocationEvents(
  data: IntermediateData | InvocationEvents | undefined,
): data is InvocationEvents {
  return data !== undefined && 'invocationEvents' in data;
}

/** Returns true when `data` is an {@link IntermediateData} container. */
export function isIntermediateData(
  data: IntermediateData | InvocationEvents | undefined,
): data is IntermediateData {
  return data !== undefined && 'toolUses' in data;
}

/**
 * Returns the tool calls recorded in the intermediate data of an invocation,
 * in chronological order.
 *
 * @param intermediateData The intermediate data to read.
 * @returns The function calls, or an empty array when there are none.
 */
export function getAllToolCalls(
  intermediateData: IntermediateData | InvocationEvents | undefined,
): FunctionCall[] {
  if (isIntermediateData(intermediateData)) {
    return intermediateData.toolUses;
  }
  if (!isInvocationEvents(intermediateData)) {
    return [];
  }
  return intermediateData.invocationEvents.flatMap((event) =>
    (event.content?.parts ?? []).flatMap((part) =>
      part.functionCall ? [part.functionCall] : [],
    ),
  );
}
