import {
  createEvent,
  createEventActions,
  CreateEventParams,
  Event,
  getFunctionCalls,
  getFunctionResponses,
  InputValidationError,
  REQUEST_CONFIRMATION_FUNCTION_CALL_NAME,
  REQUEST_CREDENTIAL_FUNCTION_CALL_NAME,
  REQUEST_INPUT_FUNCTION_CALL_NAME,
} from '@google/adk';
import {Content, Part} from '@google/genai';

/**
 * Function names that only ADK emits. A client may not import events that use
 * them, because ADK would treat them as its own pending requests.
 */
const ADK_RESERVED_FUNCTION_NAMES: ReadonlySet<string> = new Set([
  REQUEST_CONFIRMATION_FUNCTION_CALL_NAME,
  REQUEST_CREDENTIAL_FUNCTION_CALL_NAME,
  REQUEST_INPUT_FUNCTION_CALL_NAME,
]);

/** Event action fields whose default value is an empty map. */
const DEFAULT_ACTION_MAP_KEYS: ReadonlySet<string> = new Set([
  'stateDelta',
  'artifactDelta',
  'requestedAuthConfigs',
  'requestedToolConfirmations',
]);

/** Top-level event fields that must be strings when present. */
const STRING_EVENT_FIELDS: ReadonlySet<string> = new Set([
  'id',
  'invocationId',
  'author',
  'branch',
  'errorCode',
  'errorMessage',
  'finishReason',
  'modelVersion',
  'interactionId',
  'liveSessionId',
  'isolationScope',
]);

/** Top-level event fields that must be booleans when present. */
const BOOLEAN_EVENT_FIELDS: ReadonlySet<string> = new Set([
  'partial',
  'turnComplete',
  'interrupted',
]);

/**
 * Top-level event fields that hold SDK objects. Their nested keys are
 * converted to camelCase.
 */
const SDK_OBJECT_EVENT_FIELDS: ReadonlySet<string> = new Set([
  'usageMetadata',
  'groundingMetadata',
  'citationMetadata',
  'nodeInfo',
  'inputTranscription',
  'outputTranscription',
  'liveSessionResumptionUpdate',
  'goAway',
]);

/**
 * Top-level event fields that hold user-defined values. They are copied
 * without changing their keys.
 */
const USER_VALUE_EVENT_FIELDS: ReadonlySet<string> = new Set([
  'output',
  'route',
]);

/** Part fields that hold user-defined values. */
const USER_VALUE_PART_FIELDS: ReadonlySet<string> = new Set(['partMetadata']);

/** The parsed body of a create-session request. */
export interface CreateSessionBody {
  /** The initial session state. Empty when the request has none. */
  state: Record<string, unknown>;
  /** The requested session ID, trimmed. Undefined when none was given. */
  sessionId?: string;
  /** The events to append to the new session, in order. */
  events: Event[];
}

/**
 * Reports whether `value` is a non-null object that is not an array.
 */
function isPlainRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function toCamelCase(key: string): string {
  return key.replace(/_([a-z0-9])/g, (_, c: string) => c.toUpperCase());
}

/**
 * Converts the keys of every plain object in `value` to camelCase.
 */
function camelCaseKeysDeep(value: unknown): unknown {
  if (Array.isArray(value)) {
    return value.map(camelCaseKeysDeep);
  }
  if (!isPlainRecord(value)) {
    return value;
  }
  const result: Record<string, unknown> = {};
  for (const [key, nested] of camelCaseEntries(value)) {
    result[key] = camelCaseKeysDeep(nested);
  }
  return result;
}

/**
 * Returns the entries of `record` with camelCase keys. When a record has both
 * spellings of one key, the camelCase spelling wins.
 */
function camelCaseEntries(
  record: Record<string, unknown>,
): Array<[string, unknown]> {
  const entries: Array<[string, unknown]> = [];
  for (const [key, value] of Object.entries(record)) {
    // Assigning `__proto__` would replace the prototype of the new object.
    if (key === '__proto__') {
      continue;
    }
    const camelKey = toCamelCase(key);
    if (camelKey !== key && Object.hasOwn(record, camelKey)) {
      continue;
    }
    entries.push([camelKey, value]);
  }
  return entries;
}

function isAbsent(value: unknown): value is undefined | null {
  return value === undefined || value === null;
}

/**
 * Parses the body of a create-session request.
 *
 * @param body The parsed JSON request body.
 * @returns The state, session ID, and validated events.
 * @throws InputValidationError if the body, `state`, `sessionId`, or `events`
 *     has the wrong shape, or an event claims to be generated by ADK.
 */
export function parseCreateSessionBody(body: unknown): CreateSessionBody {
  if (isAbsent(body)) {
    return {state: {}, events: []};
  }
  if (!isPlainRecord(body)) {
    throw new InputValidationError(
      'Invalid create session request: expected a JSON object.',
    );
  }

  const rawState = body['state'];
  if (!isAbsent(rawState) && !isPlainRecord(rawState)) {
    throw new InputValidationError(
      'Invalid create session request: state must be an object.',
    );
  }

  const sessionId =
    parseSessionId(body['sessionId']) ?? parseSessionId(body['session_id']);

  return {
    state: rawState ?? {},
    ...(sessionId !== undefined ? {sessionId} : {}),
    events: validateAndNormalizeSessionEvents(body['events']),
  };
}

function parseSessionId(rawSessionId: unknown): string | undefined {
  if (isAbsent(rawSessionId)) {
    return undefined;
  }
  if (typeof rawSessionId !== 'string') {
    throw new InputValidationError(
      'Invalid create session request: sessionId must be a string.',
    );
  }
  const sessionId = rawSessionId.trim();
  return sessionId.length > 0 ? sessionId : undefined;
}

/**
 * Validates and normalizes events a client sends to seed a new session.
 *
 * Accepts camelCase and snake_case field names. Ordinary text, tool calls, and
 * tool responses are allowed, so a conversation that used tools can be
 * restored. Events that carry long-running tool IDs, event actions, or ADK
 * protocol function calls are rejected, because only ADK may create them.
 *
 * @param rawEvents The `events` value from the request body.
 * @returns The events, in order. Empty when `rawEvents` is absent.
 * @throws InputValidationError if an event has the wrong shape or claims to be
 *     generated by ADK.
 */
export function validateAndNormalizeSessionEvents(rawEvents: unknown): Event[] {
  if (isAbsent(rawEvents)) {
    return [];
  }
  if (!Array.isArray(rawEvents)) {
    throw new InputValidationError(
      'Invalid session initialization events: expected an array.',
    );
  }
  return rawEvents.map((rawEvent, eventIndex) =>
    normalizeSessionEvent(rawEvent, eventIndex),
  );
}

function normalizeSessionEvent(rawEvent: unknown, eventIndex: number): Event {
  if (!isPlainRecord(rawEvent)) {
    throw invalidEventError(eventIndex, 'expected an object');
  }

  // Check both spellings, so an empty camelCase list cannot hide a non-empty
  // snake_case one.
  for (const key of ['longRunningToolIds', 'long_running_tool_ids']) {
    validateLongRunningToolIds(rawEvent[key], eventIndex);
  }

  const rawActions = rawEvent['actions'];
  if (!isAbsent(rawActions)) {
    if (!isPlainRecord(rawActions) || hasNonDefaultActions(rawActions)) {
      throw new InputValidationError(
        `Session initialization event ${eventIndex} cannot include event actions.`,
      );
    }
  }

  const params: Record<string, unknown> = {};
  for (const [key, value] of camelCaseEntries(rawEvent)) {
    if (isAbsent(value)) {
      continue;
    }
    if (STRING_EVENT_FIELDS.has(key)) {
      if (typeof value !== 'string') {
        throw invalidEventError(eventIndex, `${key} must be a string`);
      }
      params[key] = value;
    } else if (BOOLEAN_EVENT_FIELDS.has(key)) {
      if (typeof value !== 'boolean') {
        throw invalidEventError(eventIndex, `${key} must be a boolean`);
      }
      params[key] = value;
    } else if (key === 'timestamp') {
      if (typeof value !== 'number' || !Number.isFinite(value)) {
        throw invalidEventError(eventIndex, 'timestamp must be a number');
      }
      params[key] = value;
    } else if (key === 'content') {
      params[key] = normalizeContent(value, eventIndex);
    } else if (key === 'customMetadata') {
      if (!isPlainRecord(value)) {
        throw invalidEventError(eventIndex, 'customMetadata must be an object');
      }
      params[key] = value;
    } else if (SDK_OBJECT_EVENT_FIELDS.has(key)) {
      if (!isPlainRecord(value)) {
        throw invalidEventError(eventIndex, `${key} must be an object`);
      }
      params[key] = camelCaseKeysDeep(value);
    } else if (USER_VALUE_EVENT_FIELDS.has(key)) {
      params[key] = value;
    }
    // `actions` and `longRunningToolIds` were validated above and are replaced
    // by their defaults. Unknown fields are dropped.
  }

  const event = createEvent({
    ...(params as CreateEventParams),
    actions: createEventActions(),
    longRunningToolIds: [],
  });

  const functionNames = [
    ...getFunctionCalls(event).map((call) => call.name),
    ...getFunctionResponses(event).map((response) => response.name),
  ];
  if (
    functionNames.some(
      (name) => name !== undefined && ADK_RESERVED_FUNCTION_NAMES.has(name),
    )
  ) {
    throw new InputValidationError(
      `Session initialization event ${eventIndex} cannot include ADK protocol function calls.`,
    );
  }

  return event;
}

function validateLongRunningToolIds(value: unknown, eventIndex: number): void {
  if (isAbsent(value)) {
    return;
  }
  if (
    !Array.isArray(value) ||
    !value.every((toolId) => typeof toolId === 'string')
  ) {
    throw invalidEventError(
      eventIndex,
      'longRunningToolIds must be an array of strings',
    );
  }
  if (value.length > 0) {
    throw new InputValidationError(
      `Session initialization event ${eventIndex} cannot include long-running tool IDs.`,
    );
  }
}

function hasNonDefaultActions(rawActions: Record<string, unknown>): boolean {
  for (const [key, value] of Object.entries(rawActions)) {
    if (isAbsent(value)) {
      continue;
    }
    if (!DEFAULT_ACTION_MAP_KEYS.has(toCamelCase(key))) {
      return true;
    }
    if (!isPlainRecord(value) || Object.keys(value).length > 0) {
      return true;
    }
  }
  return false;
}

function normalizeContent(rawContent: unknown, eventIndex: number): Content {
  if (!isPlainRecord(rawContent)) {
    throw invalidEventError(eventIndex, 'content must be an object');
  }
  const content: Content = {};
  const role = rawContent['role'];
  if (!isAbsent(role)) {
    if (typeof role !== 'string') {
      throw invalidEventError(eventIndex, 'content.role must be a string');
    }
    content.role = role;
  }
  const rawParts = rawContent['parts'];
  if (!isAbsent(rawParts)) {
    if (!Array.isArray(rawParts)) {
      throw invalidEventError(eventIndex, 'content.parts must be an array');
    }
    content.parts = rawParts.map((rawPart, partIndex) =>
      normalizePart(rawPart, eventIndex, partIndex),
    );
  }
  return content;
}

function normalizePart(
  rawPart: unknown,
  eventIndex: number,
  partIndex: number,
): Part {
  if (!isPlainRecord(rawPart)) {
    throw invalidEventError(
      eventIndex,
      `content.parts[${partIndex}] must be an object`,
    );
  }
  const part: Record<string, unknown> = {};
  for (const [key, value] of camelCaseEntries(rawPart)) {
    if (isAbsent(value)) {
      continue;
    }
    if (key === 'functionCall' || key === 'functionResponse') {
      part[key] = normalizeFunctionPayload(
        value,
        key === 'functionCall' ? 'args' : 'response',
        `content.parts[${partIndex}].${key}`,
        eventIndex,
      );
    } else if (USER_VALUE_PART_FIELDS.has(key)) {
      part[key] = value;
    } else {
      part[key] = camelCaseKeysDeep(value);
    }
  }
  return part as Part;
}

/**
 * Normalizes a `functionCall` or `functionResponse`, leaving the keys of its
 * user-defined payload (`args` or `response`) unchanged.
 */
function normalizeFunctionPayload(
  value: unknown,
  payloadKey: 'args' | 'response',
  path: string,
  eventIndex: number,
): Record<string, unknown> {
  if (!isPlainRecord(value) || typeof value['name'] !== 'string') {
    throw invalidEventError(
      eventIndex,
      `${path} must be an object with a string name`,
    );
  }
  const result: Record<string, unknown> = {};
  for (const [key, nested] of camelCaseEntries(value)) {
    result[key] = key === payloadKey ? nested : camelCaseKeysDeep(nested);
  }
  return result;
}

function invalidEventError(
  eventIndex: number,
  reason: string,
): InputValidationError {
  return new InputValidationError(
    `Invalid session initialization event ${eventIndex}: ${reason}.`,
  );
}
